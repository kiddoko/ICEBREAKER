/** Render a word in big letters. Unknown characters become spaces. */
export function bigText(word: string): string[] {
  const rows = ["", "", "", "", "", ""];
  for (const ch of word.toUpperCase()) {
    const g = FONT[ch] ?? FONT[" "];
    for (let i = 0; i < 6; i++) rows[i] += g[i];
  }
  return rows;
}

